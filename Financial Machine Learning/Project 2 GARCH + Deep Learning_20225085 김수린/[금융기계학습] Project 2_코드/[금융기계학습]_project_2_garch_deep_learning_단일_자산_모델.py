def robust_qlike_loss(y_true, y_pred):
    epsilon = 1e-6
    y_true = K.maximum(y_true, epsilon)
    y_pred = K.maximum(y_pred, epsilon)
    return K.mean(y_true / y_pred - K.log(y_true / y_pred) - 1)

