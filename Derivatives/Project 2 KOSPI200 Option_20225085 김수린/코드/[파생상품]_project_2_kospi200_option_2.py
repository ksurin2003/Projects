        # Y축 2 (우측): 스트래들 가격
        ax2 = ax1.twinx()
        sns.lineplot(data=daily_straddle_summary, x=daily_straddle_summary.index, y='Avg_Straddle_Price', label='Average ATM Straddle Price', color='red', ax=ax2)
